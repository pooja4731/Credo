const mongoose = require("mongoose");

const certificateSchema = new mongoose.Schema(
  {
    // Human-readable unique ID, e.g. CRD-2026-CSE-00123
    certificateId: { type: String, required: true, unique: true, trim: true },

    student: { type: mongoose.Schema.Types.ObjectId, ref: "User" },
    studentName: { type: String, required: true, trim: true },
    rollNumber: { type: String, required: true, trim: true },
    department: { type: String, required: true, trim: true },
    degree: { type: String, required: true, trim: true },

    // What kind of credential this is. "degree" keeps the original shape;
    // the others carry their extra fields in typeDetails so the schema
    // doesn't need to grow a new top-level field per certificate type.
    certificateType: {
      type: String,
      enum: ["degree", "internship", "course", "competition", "other"],
      default: "degree",
    },
    typeDetails: {
      // Internship
      organization: { type: String, trim: true },
      role: { type: String, trim: true },
      startDate: { type: Date },
      endDate: { type: Date },
      // Course
      courseName: { type: String, trim: true },
      provider: { type: String, trim: true },
      durationHours: { type: Number },
      grade: { type: String, trim: true },
      // Competition / achievement
      eventName: { type: String, trim: true },
      position: { type: String, trim: true },
      category: { type: String, trim: true },
      // Free-form catch-all for "other" or any type-specific extras
      description: { type: String, trim: true },
    },

    // Where this record came from: freshly generated by Credo, or an
    // institution's existing/legacy certificate that was uploaded and
    // registered for verification without Credo generating the PDF.
    source: {
      type: String,
      enum: ["issued", "registered_existing"],
      default: "issued",
    },

    institution: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Institution",
      required: true,
    },

    issueDate: { type: Date, required: true, default: Date.now },

    // Integrity + storage
    certificateHash: { type: String, required: true }, // SHA-256 hex digest
    ipfsCID: { type: String, required: true },
    ipfsPdfUrl: { type: String },
    ipfsJsonUrl: { type: String },
    qrCodeUrl: { type: String },
    localPdfPath: { type: String },

    // Populated only for source === "registered_existing": the hash and
    // IPFS location of the *original* uploaded file (not a Credo-
    // generated PDF), so re-verification can be done against the exact
    // bytes the institution submitted.
    originalFile: {
      fileHash: { type: String }, // SHA-256 hex digest of the raw uploaded bytes
      mimeType: { type: String },
      originalName: { type: String },
      ipfsCID: { type: String },
      ipfsUrl: { type: String },
    },

    // On-chain reference
    blockchain: {
      certificateIdHash: { type: String }, // bytes32 keccak256(certificateId), used as on-chain key
      transactionHash: { type: String },
      blockNumber: { type: Number },
      contractAddress: { type: String },
      issuerWallet: { type: String },
      network: { type: String },
    },

    status: {
      type: String,
      enum: ["issued", "revoked"],
      default: "issued",
    },
    revokedAt: { type: Date },
    revokedReason: { type: String },

    downloadCount: { type: Number, default: 0 },
  },
  { timestamps: true }
);

certificateSchema.index({ certificateHash: 1 });
certificateSchema.index({ institution: 1, createdAt: -1 });
certificateSchema.index({ rollNumber: 1 });

module.exports = mongoose.model("Certificate", certificateSchema);
